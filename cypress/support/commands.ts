declare namespace Cypress {
    interface Chainable {
        /**
         * Get element by [data-test] attribute with optional timeout.
         * @param dataTestAttribute The value of the data-test attribute.
         * @param timeout Optional timeout in milliseconds.
         */
        getByData(dataTestAttribute: string, timeout?: number): Chainable<JQuery<HTMLElement>>;
    }
}

Cypress.Commands.add('getByData', (selector: string, timeout?: number) => {
    const options = timeout ? { timeout } : {};
    return cy.get(`[data-test="${selector}"]`, options).should('exist');
});